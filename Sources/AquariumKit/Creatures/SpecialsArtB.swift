enum JellyfishArt {
    /// The tentacle characters `add_jellyfish` picks from (`@left_tentacle_chars`).
    static let leftTentacles: [Character] = ["(", "(", "[", "/", "|"]
    /// `@right_tentacle_chars`, index for index.
    static let rightTentacles: [Character] = [")", ")", "]", "\\", "|"]

    /// `@jellyfish_image`: two frames per direction, whose three tentacle rows alternate `l r l` and
    /// `r l r`. `l` and `r` are the left and right tentacle characters.
    static func shapes(left l: Character, right r: Character) -> [[String]] {
        func frame(_ rows: [String]) -> String {
            "\n  .-.\n (o o)\n'-' '-'\n" + rows.joined(separator: "\n") + "\n"
        }
        let lrl = [" \(l) \(r) \(l)", " \(r) \(l) \(r)", " \(l) \(r) \(l)"]
        let rlr = [" \(r) \(l) \(r)", " \(l) \(r) \(l)", " \(r) \(l) \(r)"]
        return [[frame(lrl), frame(rlr)], [frame(rlr), frame(lrl)]]
    }

    /// `@jellyfish_mask`.
    static let masks: [String] = [
#"""

  BBB
 BW WB
GRG GRG
 B B B
 B B B
 B B B
"""#,
#"""

  BBB
 BW WB
GRG GRG
 B B B
 B B B
 B B B
"""#,
    ]
}
